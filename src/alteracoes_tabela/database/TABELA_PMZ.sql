SELECT 
       F.NRODIVISAO,
       F.SEQCUSTOFORNEC,
       F.SEQCOMPRADOR,
       F.SEQFAMILIA,
       F.SEQFORNECEDOR,
       N.NOMERAZAO,
       N.FANTASIA,
       P.PRINCIPAL,
       F.QTDEMBCUSTO,
       TO_CHAR(F.VLRCUSTOBASE, 'FM999999990D00', 'NLS_NUMERIC_CHARACTERS='',.''') AS VLRCUSTOBASE,
       TO_CHAR(F.VLRCUSTOLIQUIDO, 'FM999999990D00', 'NLS_NUMERIC_CHARACTERS='',.''') AS VLRCUSTOLIQUIDO,
       TO_CHAR(F.DTAINICIOVIGOR, 'DD/MM/YYYY') AS DATA_INICIO_VIGOR,
       TO_CHAR(F.DTAULTALTERACAO, 'DD-MM-YYYY HH24:MI:SS') AS DATA_ALTERACAO
       
FROM CONSINCO.MAC_CUSTOFORNECLOG F
LEFT JOIN CONSINCO.MAP_FAMFORNEC P 
        ON F.SEQFAMILIA = P.SEQFAMILIA AND F.SEQFORNECEDOR = P.SEQFORNECEDOR
LEFT JOIN CONSINCO.GE_PESSOA N 
        ON F.SEQFORNECEDOR = N.SEQPESSOA
WHERE NROEMPRESA = 0
      AND F.DTAULTALTERACAO >= TO_DATE('01/08/2023', 'DD/MM/YYYY')
      AND P.PRINCIPAL = 'S'
 
ORDER BY 
      F.NRODIVISAO ASC, 
      F.SEQFAMILIA ASC, 
      F.SEQFORNECEDOR ASC, 
      F.DTAINICIOVIGOR DESC,
      F.DTAULTALTERACAO DESC